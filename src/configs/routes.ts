import type { NavItem } from "@/types/nav.types";

/** Prefix for links that scroll to a section on the homepage ("/#projects"). */
export const HOME_SECTION_PREFIX = "/#";

/** Homepage sections that the header and other pages link to. */
export const HOME_SECTION_IDS = {
  about: "about",
  experience: "experience",
  projects: "projects",
  skills: "skills",
} as const;

export type HomeSectionId =
  (typeof HOME_SECTION_IDS)[keyof typeof HOME_SECTION_IDS];

/** Every internal path on the site. Dynamic paths are built by the helpers. */
export const ROUTES = {
  about: "/about",
  blog: "/blog",
  /** Page 1 of the blog is /blog itself; later pages live at /blog/page/N. */
  blogPage: (page: number) => (page <= 1 ? "/blog" : `/blog/page/${page}`),
  blogPost: (slug: string) => `/blog/${slug}`,
  blogTag: (tagSlug: string) => `/blog/tag/${tagSlug}`,
  contact: "/contact",
  favicon: "/favicon.ico",
  home: "/",
  homeSection: (id: HomeSectionId) => `${HOME_SECTION_PREFIX}${id}`,
  ogImage: "/opengraph-image",
  projects: "/projects",
  resume: "/resume",
  /** Generated by app/resume.pdf/route.ts. */
  resumePdf: "/resume.pdf",
  rss: "/rss.xml",
  uses: "/uses",
} as const;

/**
 * Reads the section id out of a homepage section link.
 *
 * @param href - A nav link, e.g. "/#projects" or "/blog".
 * @returns "projects" for "/#projects"; null for links to other pages.
 */
export function getHomeSectionId(href: string): string | null {
  return href.startsWith(HOME_SECTION_PREFIX)
    ? href.slice(HOME_SECTION_PREFIX.length)
    : null;
}

/**
 * Header navigation. Section items scroll to a section on the homepage (and
 * light up while that section is on screen); the rest are separate pages.
 */
export const MAIN_NAV: readonly NavItem[] = [
  { href: ROUTES.homeSection(HOME_SECTION_IDS.projects), title: "Projects" },
  {
    href: ROUTES.homeSection(HOME_SECTION_IDS.experience),
    title: "Experience",
  },
  { href: ROUTES.homeSection(HOME_SECTION_IDS.about), title: "About" },
  { href: ROUTES.homeSection(HOME_SECTION_IDS.skills), title: "Skills" },
  { href: ROUTES.blog, title: "Blog" },
  { href: ROUTES.contact, title: "Contact" },
];
